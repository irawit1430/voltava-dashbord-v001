import { describe, it, expect, beforeEach, afterEach } from 'vitest';
import { isEmailAllowed, saveAllowedEmails, getAllowedEmails, verifySessionToken, generateSessionToken } from './auth';
import jwt from 'jsonwebtoken';
import { AUTH_CONFIG } from './config';
import type { User } from './types';

describe('Auth Module - isEmailAllowed', () => {
  let originalAllowlist: string[];

  beforeEach(() => {
    // Store original allowlist to restore it after each test
    originalAllowlist = [...getAllowedEmails()];
    // Set a controlled allowlist for testing
    saveAllowedEmails(['admin@voltava.com', 'user.name@example.org']);
  });

  afterEach(() => {
    // Restore the original allowlist
    saveAllowedEmails(originalAllowlist);
  });

  it('should return true for an exact match', () => {
    expect(isEmailAllowed('admin@voltava.com')).toBe(true);
  });

  it('should return true for a case-insensitive match', () => {
    expect(isEmailAllowed('ADMIN@VOLTAVA.COM')).toBe(true);
    expect(isEmailAllowed('User.Name@Example.Org')).toBe(true);
  });

  it('should return true for emails with leading and trailing whitespace', () => {
    expect(isEmailAllowed('  admin@voltava.com  ')).toBe(true);
    expect(isEmailAllowed('\tuser.name@example.org\n')).toBe(true);
  });

  it('should return false for emails not in the allowlist', () => {
    expect(isEmailAllowed('hacker@evil.com')).toBe(false);
    expect(isEmailAllowed('admin@voltava.co')).toBe(false); // typo
  });

  it('should return false for an empty string', () => {
    expect(isEmailAllowed('')).toBe(false);
  });

  it('should return false for a whitespace-only string', () => {
    expect(isEmailAllowed('   ')).toBe(false);
  });
});


describe('Auth Module - verifySessionToken', () => {
  const mockUser: User = {
    email: 'test@example.com',
    name: 'Test User',
    picture: 'http://example.com/pic.jpg',
    role: 'admin',
  };

  it('should return the decoded payload for a valid token generated by generateSessionToken', () => {
    const token = generateSessionToken(mockUser);
    const payload = verifySessionToken(token);
    expect(payload).not.toBeNull();
    expect(payload?.email).toBe(mockUser.email);
    expect(payload?.name).toBe(mockUser.name);
    expect(payload?.picture).toBe(mockUser.picture);
    expect(payload?.role).toBe(mockUser.role);
  });

  it('should return null for a completely invalid token string', () => {
    expect(verifySessionToken('not.a.real.token')).toBeNull();
  });

  it('should return null for an expired token', () => {
    // Sign a token that expired 1 hour ago
    const expiredToken = jwt.sign(mockUser, AUTH_CONFIG.JWT_SECRET, {
      expiresIn: '-1h',
      algorithm: 'HS256',
    });
    expect(verifySessionToken(expiredToken)).toBeNull();
  });

  it('should return null if signed with the wrong secret', () => {
    const badToken = jwt.sign(mockUser, 'wrong-secret', {
      expiresIn: '1h',
      algorithm: 'HS256',
    });
    expect(verifySessionToken(badToken)).toBeNull();
  });

  it('should return null if signed with a different algorithm', () => {
    const badToken = jwt.sign(mockUser, AUTH_CONFIG.JWT_SECRET, {
      expiresIn: '1h',
      algorithm: 'HS512',
    });
    expect(verifySessionToken(badToken)).toBeNull();
  });
});
